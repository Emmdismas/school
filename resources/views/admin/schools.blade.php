                generatePrimaryFeesTable();
            } else if (selectedType === 'secondary') {
                document.getElementById('secondary-subjects').style.display = 'block';
                generateSecondarySubjectsTable();
                generateSecondaryFeesTable();
            } else if (selectedType === 'advance') {
                document.getElementById('advance-subjects').style.display = 'block';
                generateAdvanceCombinationsTable();
                generateAdvanceFeesTable();
