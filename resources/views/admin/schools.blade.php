      document.addEventListener('input', function (e) {
    if (e.target.name.includes('tuition_fee_') || e.target.name.includes('other_fee_')) {
        const baseName = e.target.name.split('_').slice(2).join('_');

        const tuition = parseFloat(document.querySelector(`input[name="tuition_fee_${baseName}"]`).value) || 0;
        const other = parseFloat(document.querySelector(`input[name="other_fee_${baseName}"]`).value) || 0;

        const total = tuition + other;

        // Update visible text
        const totalSpan = document.getElementById(`total_fee_${baseName}`);
        if (totalSpan) {
            totalSpan.textContent = total.toLocaleString(); // With commas
        }

        // Update hidden input
        const hiddenInput = document.getElementById(`hidden_total_fee_${baseName}`);
        if (hiddenInput) {
            hiddenInput.value = total;
        }
    }
});




